class TestBlockRefusesProtected:
    def test_local_block_refuses_the_gateway(self, protected):
        assert _make_fw().block_ip(GATEWAY) is False

    def test_local_block_refuses_this_host(self, protected):
        assert _make_fw().block_ip(OWN_IP) is False

    def test_local_block_refuses_the_resolver(self, protected):
        assert _make_fw().block_ip(RESOLVER) is False

    def test_external_ip_is_still_blockable(self, protected):
        assert _make_fw(dry_run=True).block_ip(EXTERNAL) is True

    def test_refusal_touches_no_firewall_command(self, protected, monkeypatch):
        """The refusal must land before any iptables/nft call is attempted."""
        import response.firewall as fw

        def _forbidden(*args, **kwargs):
            raise AssertionError(f"firewall command attempted: {args}")

        # Build in dry-run (so __init__ probes nothing), then arm it: from here
        # on any subprocess call is the failure under test.
        fwm = _make_fw(dry_run=True)
        fwm.dry_run = False
        monkeypatch.setattr(fw.subprocess, "run", _forbidden)
        assert fwm.block_ip(GATEWAY) is False

    def test_bridge_block_refuses_protected_and_adds_no_rule(self, protected):
        fw = _make_fw(dry_run=False)
        fw.bridge_block_ip(GATEWAY)
        assert GATEWAY not in fw._bridge_blocked

    def test_is_protected_predicate(self, protected):
        from response.firewall import is_protected
        assert is_protected(GATEWAY) is True
        assert is_protected(EXTERNAL) is False
        assert is_protected("") is False
        assert is_protected(None) is False
        assert is_protected(12345) is False

    def test_method_matches_module_predicate(self, protected):
        fw = _make_fw()
        assert fw.is_protected_ip(GATEWAY) is True
        assert fw.is_protected_ip(EXTERNAL) is False

    def test_guard_degrades_quietly_if_the_set_cannot_be_computed(self, monkeypatch):
        """A failure to compute the set must not stop legitimate blocking."""
        import response.firewall as fw
        monkeypatch.setattr(fw, "_protected_ips", lambda: frozenset())
        assert _make_fw().block_ip(EXTERNAL) is True


