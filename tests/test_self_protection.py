class TestAddressParsing:
    # The real /proc/net/route shape from this machine (Kali, wlan0).
    ROUTE = (
        "Iface\tDestination\tGateway \tFlags\tRefCnt\tUse\tMetric\tMask\t\tMTU\tWindow\tIRTT\n"
        "wlan0\t00000000\t0101A8C0\t0003\t0\t0\t600\t00000000\t0\t0\t0\n"
        "wlan0\t0001A8C0\t00000000\t0001\t0\t0\t600\t00FFFFFF\t0\t0\t0\n"
    )

    def _route(self, tmp_path, text):
        path = tmp_path / "route"
        path.write_text(text)
        return str(path)

    def test_parses_the_default_route_gateway(self, tmp_path):
        from utils.interface import default_gateway
        assert default_gateway(self._route(tmp_path, self.ROUTE)) == GATEWAY

    def test_no_default_route_is_not_an_error(self, tmp_path):
        from utils.interface import default_gateway
        text = "Iface\tDestination\tGateway\nwlan0\t0001A8C0\t00000000\t0001\n"
        assert default_gateway(self._route(tmp_path, text)) == ""

    def test_on_link_zero_gateway_is_skipped(self, tmp_path):
        """A 0.0.0.0 gateway is an on-link route, not a next hop."""
        from utils.interface import default_gateway
        text = "Iface\tDestination\tGateway\nwlan0\t00000000\t00000000\t0001\n"
        assert default_gateway(self._route(tmp_path, text)) == ""

    def test_missing_file_is_not_an_error(self, tmp_path):
        from utils.interface import default_gateway
        assert default_gateway(str(tmp_path / "absent")) == ""

    def test_resolv_conf_keeps_ipv4_and_drops_ipv6(self, tmp_path):
        from utils.interface import dns_servers
        path = tmp_path / "resolv.conf"
        path.write_text(
            "# Generated by NetworkManager\n"
            "search domain.name\n"
            f"nameserver {GATEWAY}   # inline comment\n"
            "nameserver 2401:4900:50:9::7bd\n"
            f"nameserver {RESOLVER}\n"
            f"nameserver {GATEWAY}\n"  # duplicate
            "nameserver\n"  # malformed
        )
        assert dns_servers(str(path)) == [GATEWAY, RESOLVER]

    def test_missing_resolv_conf_is_not_an_error(self, tmp_path):
        from utils.interface import dns_servers
        assert dns_servers(str(tmp_path / "absent")) == []


