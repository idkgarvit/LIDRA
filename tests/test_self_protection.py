class TestBlockRecordingMatchesReality:
    """`lidra blocks` / `lidra status` must not report a block that is not real.

    Dry-run is the shipped default (``response.dry_run: true``) and means "log
    every detection, never block". ``block_ip`` returns success in dry-run
    without writing a kernel rule, so the DB row must not be marked applied —
    otherwise the status line reports an active block that does not exist.
    """

    def _stub(self, commands, monkeypatch, tmp_path, dry_run):
        from database.db import LIDRADatabase

        db = LIDRADatabase(str(tmp_path / "lidra.db"))

        class _Firewall:
            def block_ip(self, ip, ttl_seconds=0):
                return True

        _Firewall.dry_run = dry_run
        monkeypatch.setattr(commands, "_firewall", _Firewall)
        monkeypatch.setattr(commands, "_open_db", lambda: db)
        return db

    @staticmethod
    def _applied(db, ip):
        row = db._get_connection().execute(
            "SELECT applied FROM blocks WHERE ip_address = ?", (ip,)
        ).fetchone()
        assert row is not None, "the block should still be recorded as evidence"
        return row["applied"]

    def test_dry_run_block_is_recorded_but_not_applied(self, protected, tmp_path,
                                                       monkeypatch):
        import cli.commands as commands
        from response.blocklist import Blocklist

        db = self._stub(commands, monkeypatch, tmp_path, dry_run=True)
        assert commands.cmd_block_ip([EXTERNAL]) is True

        assert self._applied(db, EXTERNAL) == 0
        bl = Blocklist(db)
        bl.sync_from_db()
        assert bl.get_all() == [], "dry-run block counted as an active block"

    def test_live_block_is_marked_applied(self, protected, tmp_path, monkeypatch):
        import cli.commands as commands

        db = self._stub(commands, monkeypatch, tmp_path, dry_run=False)
        assert commands.cmd_block_ip([EXTERNAL]) is True

        assert self._applied(db, EXTERNAL) == 1