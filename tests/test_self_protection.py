"""Self-protection: LIDRA must never block its own way off the network.

docs/PRODUCTION_READINESS.md section 2.3 F4 says: *block an IP that is the
operator's own gateway/DNS — expects a refusal via the ``own_ips`` guard —
test it, do not assume.*  When that line was written the guard existed only in
``FirewallManager.bridge_block_ip()`` (bridge mode), so the local/laptop paths
— ``lidra block``, the TUI command bar, the IPC socket — would happily drop the
default route. Blocking your own resolver is a self-inflicted outage and
exactly the failure class that makes an operator uninstall an IDS for good.

These tests cover the parsing that feeds the protected set, the firewall entry
points (local and bridge), and the two operator surfaces.
"""

